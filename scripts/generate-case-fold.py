"""Regenerate the reviewed Unicode table; never downloads during a build."""
import datetime
import hashlib
from pathlib import Path
import re
import urllib.request

root = Path(__file__).resolve().parents[1] / 'src/application'
url = 'https://www.unicode.org/Public/UCD/latest/ucd/'
readme = urllib.request.urlopen(url + 'ReadMe.txt').read().decode()
if not re.search(r'final data files for version [0-9.]+', readme):
    raise SystemExit('The upstream latest UCD is not final; no fallback was selected')
data = urllib.request.urlopen(url + 'CaseFolding.txt').read()
def utf16(points):
    units = []
    for point in points:
        if point < 65536:
            units.append(point)
        else:
            units.extend([0xD800 + ((point - 65536) >> 10), 0xDC00 + ((point - 65536) & 1023)])
    return ''.join('\\x%04X' % unit for unit in units)

simple = {}
for line in data.decode().splitlines():
    body = line.split('#')[0].strip()
    if not body:
        continue
    code, status, mapping, *_ = body.split(';')
    if status.strip() in ('C', 'S'):
        simple[int(code,16)] = [int(value,16) for value in mapping.split()]
rows = ['{0x%Xu, u"%s"},' % (point, utf16(simple[point])) for point in sorted(simple)]
header = ('// Generated by scripts/generate-case-fold.py; Unicode default simple folding (C + S), matching Qt search.\n'
          '// Source: ' + url + 'CaseFolding.txt\n// ' + data.decode().splitlines()[0] + '\n'
          '// SHA-256: ' + hashlib.sha256(data).hexdigest() + '\n'
          '// Resolved UTC: ' + datetime.datetime.now(datetime.timezone.utc).isoformat() + '\n'
          '// License: Unicode-3.0, see unicode-LICENSE.txt.\n')
(root / 'case_fold_data.inc').write_text(header + '\n'.join(rows) + '\n', encoding='utf-8')
(root / 'unicode-LICENSE.txt').write_bytes(urllib.request.urlopen('https://www.unicode.org/license.txt').read())
print(header, 'Mappings:', len(rows))
